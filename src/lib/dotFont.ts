export const GLYPH_ROWS = 7
const GLYPH_COLS = 5
const SPACE_COLS = 3

if (import.meta.env.DEV) {
  for (const [char, rows] of Object.entries(GLYPHS)) {
    const parts = rows.split('/')
    if (parts.length !== GLYPH_ROWS || parts.some((row) => !/^[01]{5}$/.test(row))) {
      console.error(`dotFont: glyph "${char}" must be ${GLYPH_ROWS} rows of ${GLYPH_COLS} cells`)
    }
  }
}

export type DotGrid = {
  cols: number
  rows: number
  /** Row-major, `1` where a dot is lit. */
  lit: Uint8Array
}

export function renderDotGrid(text: string): DotGrid {
  const chars = [...text.toUpperCase()]
  const glyphs = chars.map((char) => (char === ' ' ? null : (GLYPHS[char] ?? GLYPHS['?'])))

  let cols = 0
  for (const glyph of glyphs) cols += (glyph ? GLYPH_COLS : SPACE_COLS) + 1
  cols = Math.max(cols - 1, 1)

  const lit = new Uint8Array(cols * GLYPH_ROWS)
  let x = 0
  for (const glyph of glyphs) {
    if (!glyph) {
      x += SPACE_COLS + 1
      continue
    }
    glyph.split('/').forEach((row, r) => {
      for (let c = 0; c < GLYPH_COLS; c++) {
        if (row[c] === '1') lit[r * cols + x + c] = 1
      }
    })
    x += GLYPH_COLS + 1
  }

  return { cols, rows: GLYPH_ROWS, lit }
}
